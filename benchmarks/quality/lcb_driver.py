# ------------------------------------------------------------ M_eff probe
# The scheduler effective-M probe, written per case into <case>/probe_site/
# and prepended to the server's PYTHONPATH. M is the axis the residue method
# dispatches on, so this is the second, independent confirmation that the
# residue path actually engaged -- same purpose as the mext pre-gate, from
# the opposite side. Ported from the paper tree's
# result/system_eval/vllm_scheduler_meff_probe/sitecustomize.py; it must be
# a separate file because it runs inside the SERVER process, not this one.
_MEFF_PROBE_SRC = r'''"""GENERATED by benchmarks/quality/lcb_driver.py -- do not edit, do not commit.

Scheduler effective-M probe + residue-patch chain-load. Python imports only
the FIRST sitecustomize.py on sys.path; this directory is prepended ahead of
the repo root, whose own sitecustomize applies the residue patch for spawn
workers -- so it is chain-loaded here rather than silently shadowed.
"""
import atexit, importlib.util, json, os, signal, sys, threading, time
from pathlib import Path

_REPO_ROOT = Path("@@REPO_ROOT@@")
_LOG_DIR = os.environ.get("VLLM_SCHED_MEFF_LOG_DIR", "")
_ENABLE_FILE = os.environ.get("VLLM_SCHED_MEFF_ENABLE_FILE", "")
_FLUSH_EVERY = int(os.environ.get("VLLM_SCHED_MEFF_FLUSH_EVERY", "256"))
_THRESHOLDS = (1, 2, 4, 8, 16, 32, 63, 64, 128, 256, 512, 1024, 2048, 4096, 8192)
_LOCK = threading.RLock()
_C = {"num_forward_steps": 0, "num_m_eff_lt_64": 0, "num_m_eff_le_64": 0,
      "sum_m_eff": 0, "max_m_eff": 0, "histogram": {}}
_LAST_FLUSH = 0


def _chain_load(path, name):
    if not path.exists():
        return
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        return
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)


def _summary():
    total = _C["num_forward_steps"]
    return {"type": "scheduler_meff_summary", "pid": os.getpid(),
            "time_ns": time.time_ns(), "num_forward_steps": total,
            "num_m_eff_lt_64": _C["num_m_eff_lt_64"],
            "num_m_eff_le_64": _C["num_m_eff_le_64"],
            "frac_m_eff_lt_64": _C["num_m_eff_lt_64"] / total if total else 0.0,
            "frac_m_eff_le_64": _C["num_m_eff_le_64"] / total if total else 0.0,
            "mean_m_eff": _C["sum_m_eff"] / total if total else 0.0,
            "max_m_eff": _C["max_m_eff"], "histogram": dict(_C["histogram"])}


def _write_summary():
    if not _LOG_DIR:
        return
    try:
        d = Path(_LOG_DIR)
        d.mkdir(parents=True, exist_ok=True)
        final = d / f"scheduler_meff_summary_pid{os.getpid()}.json"
        tmp = final.with_suffix(".json.tmp")
        tmp.write_text(json.dumps(_summary(), indent=2, sort_keys=True) + "\n")
        tmp.replace(final)
    except OSError:
        pass  # a failed flush must never take the server down with it


def _observe(scheduler_output):
    global _LAST_FLUSH
    if not _LOG_DIR or (_ENABLE_FILE and not os.path.exists(_ENABLE_FILE)):
        return
    m_eff = int(getattr(scheduler_output, "total_num_scheduled_tokens", 0) or 0)
    if m_eff <= 0:
        return
    with _LOCK:
        _C["num_forward_steps"] += 1
        _C["num_m_eff_lt_64"] += int(m_eff < 64)
        _C["num_m_eff_le_64"] += int(m_eff <= 64)
        _C["sum_m_eff"] += m_eff
        _C["max_m_eff"] = max(_C["max_m_eff"], m_eff)
        key = next((f"<= {t}" for t in _THRESHOLDS if m_eff <= t),
                   f"> {_THRESHOLDS[-1]}")
        _C["histogram"][key] = _C["histogram"].get(key, 0) + 1
        if _FLUSH_EVERY > 0 and _C["num_forward_steps"] - _LAST_FLUSH >= _FLUSH_EVERY:
            _LAST_FLUSH = _C["num_forward_steps"]
            _write_summary()


def _flush_at_exit():
    with _LOCK:
        _write_summary()


def _patch_scheduler():
    try:
        from vllm.v1.core.sched import scheduler
    except Exception:
        return False  # vllm not importable yet; the EngineCore init hook retries
    cls = getattr(scheduler, "Scheduler", None)
    if cls is None or getattr(cls, "_sched_meff_probe_patched", False):
        return cls is not None
    original = cls.schedule

    def wrapped(self, *args, **kwargs):
        out = original(self, *args, **kwargs)
        _observe(out)
        return out

    cls.schedule = wrapped
    cls._sched_meff_probe_patched = True
    return True


def _patch_engine_core():
    # Belt and braces: EngineCore.__init__ runs immediately before Scheduler
    # construction in whichever process holds the engine, so patching there
    # covers the case where the import above failed at interpreter startup.
    try:
        from vllm.v1.engine import core
    except Exception:
        return
    cls = getattr(core, "EngineCore", None)
    if cls is None or getattr(cls, "_meff_init_patched", False):
        return
    orig_init, orig_shutdown = cls.__init__, cls.shutdown

    def wrapped_init(self, *args, **kwargs):
        _patch_scheduler()
        return orig_init(self, *args, **kwargs)

    def wrapped_shutdown(self, *args, **kwargs):
        _flush_at_exit()
        return orig_shutdown(self, *args, **kwargs)

    cls.__init__ = wrapped_init
    cls.shutdown = wrapped_shutdown
    cls._meff_init_patched = True


def _install_signal_flush():
    def handler(signum, frame):
        _flush_at_exit()
        # os._exit, not SystemExit: raising from a signal handler installed at
        # sitecustomize time surfaces as "failed to import site" noise.
        os._exit(128 + int(signum))
    for signum in (signal.SIGTERM, signal.SIGINT):
        try:
            signal.signal(signum, handler)
        except (OSError, ValueError):
            pass


_chain_load(_REPO_ROOT / "sitecustomize.py", "_residue_repo_sitecustomize")
atexit.register(_flush_at_exit)
_install_signal_flush()
_patch_scheduler()
_patch_engine_core()
'''


def write_probe_site(case_out: pathlib.Path) -> pathlib.Path:
    site = case_out / "probe_site"
    site.mkdir(parents=True, exist_ok=True)
    (site / "sitecustomize.py").write_text(
        _MEFF_PROBE_SRC.replace("@@REPO_ROOT@@", str(REPO)))
    return site


def aggregate_meff(event_dir: pathlib.Path) -> dict:
    """Fold the per-pid summaries into one. Ported from the paper tree."""
    rows = []
    for p in sorted(event_dir.glob("scheduler_meff_summary_pid*.json")):
        row = json.loads(p.read_text())
        if int(row.get("num_forward_steps", 0)) > 0:
            rows.append(row)
    total = sum(int(r["num_forward_steps"]) for r in rows)
    lt64 = sum(int(r["num_m_eff_lt_64"]) for r in rows)
    le64 = sum(int(r["num_m_eff_le_64"]) for r in rows)
    hist: dict[str, int] = {}
    for r in rows:
        for k, v in (r.get("histogram") or {}).items():
            hist[k] = hist.get(k, 0) + int(v)
    return {
        "num_processes": len(rows),
        "num_forward_steps": total,
        "num_m_eff_lt_64": lt64,
        "num_m_eff_le_64": le64,
        "frac_m_eff_lt_64": lt64 / total if total else 0.0,
        "frac_m_eff_le_64": le64 / total if total else 0.0,
        "mean_m_eff": (sum(float(r["mean_m_eff"]) * int(r["num_forward_steps"])
                           for r in rows) / total) if total else 0.0,
        "max_m_eff": max((int(r["max_m_eff"]) for r in rows), default=0),
        "histogram": dict(sorted(hist.items())),
    }


# ----------------------------------------------------------- process plumbing
def alive(pid: int) -> bool:
    try:
        os.kill(pid, 0)
        return True
    except OSError:
        return False


def teardown() -> None:
    for pid in _PIDS:
        if not alive(pid):
            continue
        for sig in (signal.SIGTERM, signal.SIGKILL):
            try:
                os.killpg(pid, sig)
            except ProcessLookupError:
                break
            for _ in range(6):
                if not alive(pid):
                    break
                time.sleep(1)
            if not alive(pid):
                break
    _PIDS.clear()


def on_signal(signum, _frame) -> None:
    print(f"[lcb_driver] got signal {signum}, tearing down", flush=True)
    teardown()
    raise SystemExit(143)


def health_ok(port: int) -> bool:
    # ProxyHandler({}) so a shell-level SOCKS/HTTP proxy cannot swallow the
    # localhost health check.
    try:
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
        return opener.open(f"http://localhost:{port}/health", timeout=5).status == 200
    except Exception:
        return False


def free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def strip_proxies(env: dict) -> None:
    # lighteval -> litellm -> httpx routes through any configured proxy, even
    # for localhost when the proxy is SOCKS (NO_PROXY does not suppress SOCKS).
    # Symptom when not stripped: every request fails, all scores come back 0/N.
    env["NO_PROXY"] = env["no_proxy"] = "localhost,127.0.0.1"
    for k in ("http_proxy", "https_proxy", "all_proxy", "ftp_proxy",
              "HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY", "FTP_PROXY",
              "socks_proxy", "SOCKS_PROXY"):
        env.pop(k, None)


def write_json(path: pathlib.Path, payload) -> None:
    path.write_text(json.dumps(payload, indent=2, sort_keys=True, default=str) + "\n")


# ----------------------------------------------------------------- manifest
def load_manifest(path: str) -> dict:
    import yaml  # a vLLM dependency of the main venv; nothing new is added

    p = pathlib.Path(path)
    if not p.exists():
        raise SystemExit(f"manifest not found: {p}")
    man = yaml.safe_load(p.read_text())
    man["_path"] = str(p.resolve())
    for key in ("name", "arms"):
        if key not in man:
            raise SystemExit(f"{p}: manifest has no `{key}`")
    # lcb_4b.yaml says `task`, aime_4b.yaml says `tasks`; accept either.
    man["_tasks"] = man.get("task") or man.get("tasks")
    if not man["_tasks"]:
        raise SystemExit(f"{p}: manifest names no task (`task:` or `tasks:`)")
    # Decoding params are the manifest's to set, not this file's to default:
    # a silent default here would let two runs of "the same manifest" sample
    # differently and still look comparable.
    missing = [k for k in ("temperature", "top_p", "top_k", "max_new_tokens",
                           "max_model_len", "seed") if k not in man]
    if missing:
        raise SystemExit(f"{p}: manifest is missing decoding params: "
                         f"{', '.join(missing)}")
    return man


def resolve_arms(man: dict, models_root: str, only: str | None) -> list[dict]:
    """Absolute-ize arm paths, refusing up front on ANY missing arm -- a table
    short one column still looks like a complete table."""
    root = pathlib.Path(models_root).expanduser().resolve()
    arms = man["arms"]
    if only:
        wanted = [s.strip() for s in only.split(",") if s.strip()]
        by_id = {a["id"]: a for a in arms}
        unknown = [w for w in wanted if w not in by_id]
        if unknown:
            raise SystemExit(f"--arms names arm(s) not in the manifest: "
                             f"{', '.join(unknown)} (have: {', '.join(by_id)})")
        arms = [by_id[w] for w in wanted]
    resolved, missing = [], []
    for arm in arms:
        if "id" not in arm or "path" not in arm or "kind" not in arm:
            raise SystemExit(f"{man['_path']}: arm needs id/path/kind: {arm}")
        if arm["kind"] not in ("fp16", "residue", "modelopt_fp4"):
            raise SystemExit(f"arm {arm['id']}: unknown kind {arm['kind']!r} "
                             f"(expected fp16 | residue | modelopt_fp4)")
        full = root / arm["path"]
        if not full.exists():
            missing.append(f"    {arm['id']:<16} -> {full}")
            continue
        resolved.append(dict(arm, abs_path=str(full)))
    if missing:
        raise SystemExit(
            f"manifest {man['name']}: {len(missing)} arm path(s) not found "
            f"under --models-root {root}:\n" + "\n".join(missing))
    return resolved


# ------------------------------------------------------------- server side
def build_server_env(arm: dict, a, case_out: pathlib.Path,
                     probe_site: pathlib.Path,
                     event_dir: pathlib.Path, enable_file: pathlib.Path) -> dict:
    env = os.environ.copy()
    strip_proxies(env)
    # Start from a clean residue slate: an inherited RESIDUE_* would make the
    # served arm differ from what this file constructs AND records.
    for k in [k for k in env if k.startswith("RESIDUE_")]:
        env.pop(k)
    # Delta 3: never carried, in any form -- forcing distorted baselines, and
    # vLLM>=0.26 ignores it anyway (an internal guard test keeps it dead).
    if env.pop("VLLM_NVFP4_GEMM_BACKEND", None) is not None:
        print("[lcb_driver] dropped inherited VLLM_NVFP4_GEMM_BACKEND "
              "(dead knob; distorts baselines)", flush=True)

    if a.gpu is not None:
        env["CUDA_VISIBLE_DEVICES"] = str(a.gpu)
    env["VLLM_NO_USAGE_STATS"] = "1"
    # Every arm, not only residue ones: this knob changes the ENGINE
    # ARCHITECTURE, so setting it per-arm would split the table down the
    # middle (evalkit install_env, B2.13). Residue additionally REQUIRES it:
    # the plugin chain does not cover a spawned EngineCore on vLLM 0.26.
    env["VLLM_ENABLE_V1_MULTIPROCESSING"] = "0"
    env["VLLM_WORKER_MULTIPROC_METHOD"] = "fork"  
    
    
    env["VLLM_DISABLE_COMPILE_CACHE"] = "1"
    
    
    
    
    
    
    
    
    
    
    
    
    
    env["LIBRARY_PATH"] = "/usr/lib/x86_64-linux-gnu:" + env.get("LIBRARY_PATH", "")
    # probe_site comes first because it chain-loads the repository's
    # sitecustomize. Both package roots are required: quant lives at REPO,
    # while nvfp4 lives under csrc/nvfp4.
    env["PYTHONPATH"] = os.pathsep.join(
        [str(probe_site), str(REPO), str(REPO / "csrc")]
        + ([env["PYTHONPATH"]] if env.get("PYTHONPATH") else []))
    env["VLLM_SCHED_MEFF_LOG_DIR"] = str(event_dir)
    env["VLLM_SCHED_MEFF_ENABLE_FILE"] = str(enable_file)
    env["VLLM_SCHED_MEFF_FLUSH_EVERY"] = str(a.meff_flush_every)

    if arm["kind"] == "residue":
        env["RESIDUE_NVFP4"] = "1"
        env["RESIDUE_VLLM_MODEL_DIR"] = arm["abs_path"]
        
        
        
        
        env["RESIDUE_ENABLE_DECODE_MEXT"] = "1"
        env["RESIDUE_FORCE_DECODE_MEXT"] = "0"
        env["RESIDUE_DECODE_MEXT_MAX_M"] = str(a.mext_max_m)
        if str(arm.get("mext", "on")) == "off":
            # The plain floor from the SAME checkpoint. Neither "off" flag
            # works: ENABLE_DECODE_MEXT=0 kills loading, DECODE_MEXT_MAX_M=0
            # silently keeps residue on (the legacy branch is numerically
            # equivalent). The M threshold on the prefill switch is the one
            # compute-time kill: MIN_M=0 means every M > 0 loses its residue.
            env["RESIDUE_PREFILL_RESIDUE_OFF"] = "1"
            env["RESIDUE_PREFILL_RESIDUE_OFF_MIN_M"] = "0"
        # Cubins push modelopt_fp4 onto trtllm-gen paths that bypass or break
        # the patched linear method (vllm-integration.md rule 3).
        for var in ("FLASHINFER_CUBIN_DIR", "VLLM_HAS_FLASHINFER_CUBIN"):
            if env.pop(var, None) is not None:
                print(f"[lcb_driver] dropped {var}: incompatible with a "
                      f"residue arm", flush=True)
    return env


def build_server_cmd(arm: dict, man: dict, a, port: int) -> list[str]:
    if not VLLM_BIN.exists():
        raise SystemExit(f"vLLM entrypoint not found: {VLLM_BIN} -- the server "
                         f"runs from the MAIN venv; is .venv bootstrapped?")
    cmd = [str(VLLM_BIN), "serve", arm["abs_path"],
           "--port", str(port),
           "--dtype", a.dtype,
           # enforce_eager stays False (knob 1: non-eager is the standard).
           "--seed", str(man["seed"]),                          # knob 4
           "--max-model-len", str(man["max_model_len"]),        # knob 6
           # Knob 2, pinned. 2048 is the historical short-prompt value; LCB
           # prompts are short-to-mid so the pin does not cross the method's
           # dispatch boundary the way it would on a 16k-prompt venue.
           "--max-num-batched-tokens", str(a.max_num_batched_tokens),
           "--max-num-seqs", str(a.max_num_seqs),               # knob 10
           "--gpu-memory-utilization", str(a.gpu_mem_util),     # knob 7
           "--no-enable-flashinfer-autotune"]                   # knob 3
    if arm["kind"] in ("residue", "modelopt_fp4"):
        cmd += ["--quantization", "modelopt_fp4"]
    return cmd


def launch_server(cmd: list[str], env: dict, case_out: pathlib.Path,
                  port: int, timeout_s: int) -> None:
    with (case_out / "server.log").open("wb") as log:
        proc = subprocess.Popen(cmd, cwd=str(REPO), env=env, stdout=log,
                                stderr=subprocess.STDOUT, start_new_session=True)
    _PIDS.append(proc.pid)
    print(f"[lcb_driver] server pid={proc.pid} port={port}", flush=True)
    deadline = time.time() + timeout_s
    while time.time() < deadline:
        if health_ok(port):
            return
        returncode = proc.poll()
        if returncode is not None:
            raise RuntimeError(
                f"server exited with code {returncode} before /health became "
                f"ready -- see {case_out / 'server.log'}")
        time.sleep(2)
    raise RuntimeError(f"server not healthy after {timeout_s}s -- see "
                       f"{case_out / 'server.log'}")


def preflight_server(arm: dict, env: dict, case_out: pathlib.Path) -> dict:
    """Verify the residue package, extension ABI, and vLLM patch before serve."""
    if arm["kind"] != "residue":
        return {}
    if not SERVING_PYTHON.exists():
        raise RuntimeError(f"serving interpreter not found: {SERVING_PYTHON}")

    script = r'''import hashlib, importlib.util, json, pathlib, sys
import nvfp4, quant, torch
from nvfp4.extension import ensure_loaded
from quant.vllm_integration.patch import is_patched
assert ensure_loaded(True), "nvfp4 extension did not load"
assert is_patched(), "residue vLLM patch is not installed"
spec = importlib.util.find_spec("nvfp4._C")
origin = pathlib.Path(spec.origin).resolve() if spec and spec.origin else None
assert origin and origin.is_file(), "nvfp4._C origin is unavailable"
payload = {
    "python": sys.version.split()[0],
    "torch": torch.__version__,
    "torch_cuda": torch.version.cuda,
    "extension": str(origin),
    "extension_sha256": hashlib.sha256(origin.read_bytes()).hexdigest(),
}
print("RESINFER_PREFLIGHT_JSON=" + json.dumps(payload, sort_keys=True))
'''
    proc = subprocess.run(
        [str(SERVING_PYTHON), "-c", script], cwd=str(REPO), env=env,
        capture_output=True, text=True,
    )
    log_path = case_out / "server_preflight.log"
    log_path.write_text(proc.stdout + proc.stderr)
    if proc.returncode != 0:
        raise RuntimeError(
            f"residue server preflight exited {proc.returncode}; see {log_path}")
    marker = "RESINFER_PREFLIGHT_JSON="
    lines = [line for line in proc.stdout.splitlines() if line.startswith(marker)]
    if not lines:
        raise RuntimeError(f"server preflight produced no ABI record; see {log_path}")
    payload = json.loads(lines[-1][len(marker):])
    extension = pathlib.Path(payload["extension"])
    try:
        extension.relative_to(REPO / "csrc" / "nvfp4")
    except ValueError as exc:
        raise RuntimeError(
            f"nvfp4 extension is not from this checkout: {extension}") from exc
    payload["source_commit"] = git_head()
    return payload


# ---------------------------------------------------------------- the gates
def mext_resolved_gate(server_log: pathlib.Path, arm: dict) -> str | None:
    """Delta 4: confirm the RESOLVED mode in the server log after the server
    is up and BEFORE the first prompt. Returns an error string naming
    expected vs found, or None when confirmed."""
    text = server_log.read_text(errors="ignore") if server_log.is_file() else ""
    resolved = [ln for ln in text.splitlines()
                if "[residue:env]" in ln and "mode=" in ln
                and "WARNING" not in ln and "FATAL" not in ln]
    if not resolved:
        return (f"arm {arm['id']}: no [residue:env] resolved-mode line in "
                f"{server_log}. The residue plugin never ran in the engine "
                f"process -- the arm would serve UNPATCHED and measure the "
                f"plain floor under a method arm's name "
                f"(implementation constraints rule 1).")
    line = resolved[-1].strip()
    mext_on = str(arm.get("mext", "on")) == "on"
    if mext_on:
        # Primary signal is decode_mext=on; a mode naming mext (mext_r1) is
        # also accepted as a resolved-mode confirmation.
        if "decode_mext=on" not in line and "mode=mext" not in line:
            return (f"arm {arm['id']}: expected decode_mext=on (or a mode "
                    f"naming mext) in the resolved line; found: {line}")
        if "prefill_residue=OFF" in line:
            return (f"arm {arm['id']}: expected prefill_residue=on for a "
                    f"method arm, but the compute-time kill is engaged; "
                    f"found: {line}")
    else:
        # The mext-off floor arm relies on the compute-time kill; without it
        # the arm silently serves residue under the floor's name -- the same
        # hazard, inverted.
        if "prefill_residue=OFF" not in line:
            return (f"arm {arm['id']}: expected prefill_residue=OFF (the "
                    f"compute-time residue kill that makes this the plain "
                    f"floor); found: {line}")
    return None


def generation_provenance(server_log: pathlib.Path, server_env: dict) -> dict:
    """Did this case actually generate, or did lighteval replay a cache?

    lighteval memoises generations and replays on a config-hash hit; nothing
    in its results json says so. The only observable is that the server never
    reported generation throughput. The runtime_env fingerprint exists because
    the cache key only ever sees an HTTP endpoint: two arms differing purely
    in server-side RESIDUE_*/VLLM_* (exactly the shape of a kernel or
    patch-mode A/B) collide, and only this record distinguishes them after
    the fact."""
    served = 0
    if server_log.is_file():
        served = server_log.read_text(errors="ignore").count(
            "Avg generation throughput")
    env_fp = {k: v for k, v in sorted(server_env.items())
              if k.startswith(("RESIDUE_", "VLLM_")) or k == "CUDA_VISIBLE_DEVICES"}
    return {"generated": served > 0, "cache_replay": served == 0,
            "decode_throughput_lines": served, "runtime_env": env_fp}


# ------------------------------------------------------------- scorer side
def write_lighteval_config(arm: dict, man: dict, a, port: int,
                           case_out: pathlib.Path,
                           cache_dir: pathlib.Path | None) -> pathlib.Path:
    import yaml

    # model_name='openai/<path>': litellm sends everything after 'openai/' as
    # the OpenAI 'model' field, which vLLM matches against its model_id.
    model_parameters = {
        "model_name": f"openai/{arm['abs_path']}",
        "provider": "openai",
        "base_url": f"http://localhost:{port}/v1",
        "api_key": "dummy",  # vLLM ignores it
        "concurrent_requests": a.concurrent_requests,
        "timeout": a.request_timeout,
        "max_model_length": int(man["max_model_len"]),
        "generation_parameters": {
            "seed": int(man["seed"]),
            "temperature": float(man["temperature"]),
            "top_p": float(man["top_p"]),
            "top_k": int(man["top_k"]),
            "min_p": float(man.get("min_p", 0.0)),
            "max_new_tokens": int(man["max_new_tokens"]),
        },
    }
    if cache_dir is not None:
        # Delta 2: run-scoped, per case. Per CASE and not per run because this
        # manifest's floor arm shares a model path with a method arm -- with
        # one shared dir the second of the two would replay the first
        # (lighteval-cache.md rule 1: per-arm is REQUIRED when arms share a
        # model path).
        cache_dir.mkdir(parents=True, exist_ok=True)
        model_parameters["cache_dir"] = str(cache_dir)
    cfg_path = case_out / "lighteval_model_args.yaml"
    cfg_path.write_text(yaml.safe_dump({"model_parameters": model_parameters},
                                       sort_keys=False))
    return cfg_path


def run_lighteval(arm: dict, man: dict, a, cfg_path: pathlib.Path,
                  case_out: pathlib.Path) -> dict:
    scorer_bin = pathlib.Path(a.lighteval_env).expanduser().resolve() / "bin"
    scorer_cli, scorer_python = scorer_bin / "lighteval", scorer_bin / "python"
    if not scorer_cli.exists():
        raise SystemExit(
            f"lighteval CLI not found: {scorer_cli}; pass --lighteval-env with an installed scorer environment.")
    raw = case_out / "lighteval_raw"
    raw.mkdir(parents=True, exist_ok=True)
    tasks = a.tasks or man["_tasks"]
    cmd = [str(scorer_cli), "endpoint", "litellm", str(cfg_path), tasks,
           "--output-dir", str(raw)]
    if a.custom_tasks:
        cmd += ["--custom-tasks", str(pathlib.Path(a.custom_tasks).resolve())]
    if a.max_samples is not None:
        cmd += ["--max-samples", str(a.max_samples)]
    if a.save_details:
        cmd.append("--save-details")

    env = os.environ.copy()
    strip_proxies(env)
    env.update({
        "HF_HUB_OFFLINE": "1",
        "HF_DATASETS_OFFLINE": "1",
        "TRANSFORMERS_OFFLINE": "1",
        "HF_HUB_DISABLE_TELEMETRY": "1",
        "DISABLE_TELEMETRY": "1",
        "DO_NOT_TRACK": "1",
        "LITELLM_LOCAL_MODEL_COST_MAP": "True",
        "LITELLM_LOCAL_ANTHROPIC_BETA_HEADERS": "True",
    })
    if a.nltk_data:
        env["NLTK_DATA"] = str(pathlib.Path(a.nltk_data).expanduser().resolve())
    if a.data_root:
        env["RESINFER_EVAL_DATA_ROOT"] = str(
            pathlib.Path(a.data_root).expanduser().resolve())
    compat = REPO / "benchmarks" / "quality" / "lighteval_compat"
    env["PYTHONPATH"] = os.pathsep.join(
        [str(compat), str(REPO)]
        + ([env["PYTHONPATH"]] if env.get("PYTHONPATH") else []))
    # Shared HF cache so pre-fetched datasets are visible to the scorer venv.
    env.setdefault("HF_HOME", str(pathlib.Path.home() / ".cache" / "huggingface"))
    preflight_lighteval(env, case_out, scorer_python)
    write_json(case_out / "lighteval_invocation.json",
               {"cmd": cmd, "config": str(cfg_path), "tasks": tasks})
    print(f"[lcb_driver] scorer: {' '.join(cmd)}", flush=True)
    with (case_out / "lighteval.log").open("wb") as f:
        proc = subprocess.run(cmd, cwd=str(case_out), env=env,
                              stdout=f, stderr=subprocess.STDOUT)
    if proc.returncode != 0:
        raise RuntimeError(f"lighteval exited {proc.returncode}; see "
                           f"{case_out / 'lighteval.log'}")
    hits = sorted(raw.rglob("results_*.json"))  # nested deep: model_name has slashes
    if not hits:
        raise RuntimeError(f"no lighteval results json found under {raw}")
    if a.save_details and not list(raw.rglob("*.parquet")):
        raise RuntimeError(f"--save-details produced no parquet file under {raw}")
    return json.loads(hits[-1].read_text()).get("results", {})


def preflight_lighteval(env: dict, case_out: pathlib.Path, scorer_python: pathlib.Path) -> None:
    """Fail before task loading if the offline scorer assets are incomplete."""
    if not scorer_python.exists():
        raise RuntimeError(f"lighteval interpreter not found: {scorer_python}")
    if not env.get("NLTK_DATA"):
        raise RuntimeError(
            "Offline lighteval requires local NLTK resources; pass --nltk-data")
    script = r'''import importlib.util, pathlib
import nltk, xxhash
spec = importlib.util.find_spec("lighteval")
assert spec and spec.origin, "lighteval is not installed"
task_dir = pathlib.Path(spec.origin).resolve().parent / "tasks" / "tasks"
assert (task_dir / "tinyBenchmarks.pkl").is_file(), "tinyBenchmarks.pkl is missing"
for resource in (
    "tokenizers/punkt",
    "tokenizers/punkt_tab",
    "corpora/stopwords",
    "taggers/averaged_perceptron_tagger_eng",
):
    nltk.data.find(resource)
xxhash.xxh64("resinfer-text-compat").hexdigest()
print("lighteval offline preflight passed")
'''
    result = subprocess.run(
        [str(scorer_python), "-c", script], cwd=str(REPO), env=env,
        capture_output=True, text=True,
    )
    log_path = case_out / "lighteval_preflight.log"
    log_path.write_text(result.stdout + result.stderr)
    if result.returncode != 0:
        raise RuntimeError(
            f"lighteval offline preflight exited {result.returncode}; see {log_path}")


# ------------------------------------------------------------------ one case
def git_head() -> str | None:
    try:
        out = subprocess.run(["git", "rev-parse", "HEAD"], cwd=str(REPO),
                             capture_output=True, text=True)
        return out.stdout.strip() or None
    except OSError:
        return None


def run_case(arm: dict, man: dict, a, out_root: pathlib.Path) -> tuple[str, dict]:
    """One arm end to end. Returns (status, results)."""
    case_out = out_root / arm["id"]
    case_out.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    port = a.port or free_port()

    probe_site = write_probe_site(case_out)
    event_dir = case_out / "meff_events"
    event_dir.mkdir(exist_ok=True)
    enable_file = case_out / "meff_probe.enabled"
    enable_file.write_text("1\n")

    env = build_server_env(arm, a, case_out, probe_site, event_dir, enable_file)
    cmd = build_server_cmd(arm, man, a, port)
    cache_dir = None if a.global_cache else case_out / "lighteval_cache"

    status, results, error, resolved_line = "fail", {}, None, None
    server_preflight = {}
    server_log = case_out / "server.log"
    try:
        server_preflight = preflight_server(arm, env, case_out)
        launch_server(cmd, env, case_out, port, a.ready_timeout_sec)
        # Delta 4: the pre-gate runs after health and before the first prompt.
        if arm["kind"] == "residue":
            problem = mext_resolved_gate(server_log, arm)
            if problem:
                status, error = "fail_mext", problem
                raise RuntimeError(problem)
        if server_log.is_file():
            hits = [ln for ln in server_log.read_text(errors="ignore").splitlines()
                    if "[residue:env]" in ln and "mode=" in ln]
            resolved_line = hits[-1].strip() if hits else None
        cfg_path = write_lighteval_config(arm, man, a, port, case_out, cache_dir)
        results = run_lighteval(arm, man, a, cfg_path, case_out)
        status = "pass"
    except Exception as exc:  # recorded per case; the suite keeps going
        error = error or repr(exc)
        print(f"[lcb_driver] arm {arm['id']} FAILED: {error}", flush=True)
    finally:
        teardown()

    prov = generation_provenance(server_log, env)
    if enable_file.exists():
        enable_file.unlink()
    meff = aggregate_meff(event_dir)
    write_json(case_out / "scheduler_meff_summary.json", meff)

    if status == "pass" and prov["cache_replay"]:
        # Delta 1: a replay is a FAILURE. The numbers exist, but they are an
        # older run's generations, possibly off a different stack.
        status = "fail_replay"
        error = ("server never reported generation throughput -- lighteval "
                 "REPLAYED a cached run. Rerun without --global-cache, or "
                 "point --out somewhere fresh.")
        print(f"[lcb_driver] arm {arm['id']}: {error}", flush=True)
    if status == "pass" and meff["num_forward_steps"] == 0:
        # The probe is the second confirmation the residue path engaged; a run
        # that scored but produced no scheduler events proves nothing about M.
        status = "fail"
        error = (f"M_eff probe produced no scheduler events under {event_dir} "
                 f"on a run that generated live -- probe injection broke.")
        print(f"[lcb_driver] arm {arm['id']}: {error}", flush=True)

    wall = time.time() - t0
    write_json(case_out / "provenance.json", {
        "arm": arm["id"], "model": arm["abs_path"], "kind": arm["kind"],
        "mext": arm.get("mext"), "manifest": man["_path"],
        "git_head": git_head(),
        "server_preflight": server_preflight,
        "resolved_mode": resolved_line,
        "runtime_env": prov["runtime_env"],
        "cache_dir": str(cache_dir) if cache_dir else "GLOBAL (opted out)",
        "decode_throughput_lines": prov["decode_throughput_lines"],
        "generated": prov["generated"], "cache_replay": prov["cache_replay"],
        "wall_time_sec": round(wall, 1),
        "scheduler_meff": meff,
        "server_cmd": cmd,
        "sampling": {k: man[k] for k in
                     ("temperature", "top_p", "top_k", "max_new_tokens", "seed")},
        "engine_knobs": {
            "enforce_eager": False,
            "max_num_batched_tokens": a.max_num_batched_tokens,
            "max_num_seqs": a.max_num_seqs,
            "max_model_len": man["max_model_len"],
            "gpu_memory_utilization": a.gpu_mem_util,
            "enable_flashinfer_autotune": False,
            "seed": man["seed"],
        },
    })
    write_json(case_out / "lighteval_results.json",
               {"results": results, "provenance": prov})
    write_json(case_out / "bench_result.json", {
        "status": status, "arm": arm["id"], "model": arm["abs_path"],
        "kind": arm["kind"], "mext": arm.get("mext"),
        "tasks": a.tasks or man["_tasks"], "error": error, "results": results,
        "wall_time_sec": round(wall, 1),
    })
    for task, metrics in results.items():
        nums = {k: v for k, v in metrics.items() if isinstance(v, (int, float))}
        print(f"[lcb_driver]   {arm['id']} | {task}: {nums}", flush=True)
    return status, results


